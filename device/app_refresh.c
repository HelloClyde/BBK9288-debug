static int same(u32 address,const u8 *expected,unsigned bytes)
{
    unsigned i;
    for(i=0u;i<bytes;++i) if(R8(address+i)!=expected[i]) return 0;
    return 1;
}

int d88_app_refresh_available(void)
{
    static const u8 directory[]={0x41,0x3a,0x5c,0xcf,0xb5,0xcd,0xb3,0x5c,0xb3,0xcc,0xd0,0xf2,0x5c,0};
    static const u8 extension[]={'e','x','e',0};
    return d88_file_native_available() &&
        R32(0x02000200u)==0x021e81e8u && R32(0x02000204u)==0x021e7b54u &&
        R32(0x02000214u)==0x021e7a3cu && R32(0x021e7ad4u)==SCAN_ENTRY &&
        R32(0x021e7b90u)==POST_ENTRY && R32(0x022a9820u)==0x02068b34u &&
        same(SCAN_ENTRY,scan_wrapper_signature,sizeof(scan_wrapper_signature)) &&
        same(0x0215f5ccu,scan_helper_signature,sizeof(scan_helper_signature)) &&
        same(0x0215f4a0u,build_record_signature,sizeof(build_record_signature)) &&
        same(POST_ENTRY,post_signature,sizeof(post_signature)) &&
        same(0x021e75dcu,directory,sizeof(directory)) &&
        same(0x021e7668u,extension,sizeof(extension));
}

static int context(void)
{
    return d88_gui_jobs_context() && GP()==0u && (PSR()&0x710u)==0x10u &&
        R32(0x02068664u)==GUI_TCB && R8(0x0206866cu)==0u &&
        (R8(0x0206866du)&7u)==0u;
}

static int home_idle(u32 home)
{
    return home>=0x02000000u && home<=0x026fff20u && !(home&3u) &&
        R32(0x0202a3b8u)==home && R32(0x02038474u)==home &&
        R32(home)==0x00110001u && R32(home+0x74u)==0x0216022au &&
        R32(0x0202a3b4u)==1u && (int)R32(0x0202a3b0u)<=0 &&
        R32(0x0202a4e4u)==0u;
}

int d88_app_refresh_execute(d88_app_refresh_result *result)
{
    u32 home,hook,home_queue;
    int posted;
    if(!result) return D88_FILE_E_ARGUMENT;
    result->before_total=result->after_total=result->before_cat8=result->after_cat8=0u;
    result->scanner_calls=result->post_calls=result->post_result=result->home=0u;
    if(!context()) return D88_FILE_E_PROFILE;
    if(!d88_app_refresh_available()) return D88_FILE_E_PROFILE;
    home=R32(0x0202a3b8u);result->home=home;
    if(!home_idle(home)) return D88_FILE_E_BUSY;
    result->before_total=R32(TOTAL_COUNT);result->before_cat8=R32(GAME_COUNT);
    if(result->before_total>128u || result->before_cat8>result->before_total)
        return D88_FILE_E_PROFILE;
    hook=R32(HOOK_SLOT);home_queue=R32(home+0xdcu);
    /* SCAN may block in native filesystem calls. No CPU/dispatch lock is held,
     * and the shared job FSM owns this command until the complete result.
     * Nothing in the native record table is written on a rejected preflight.
     */
    result->scanner_calls=1u;SCAN();
    result->after_total=R32(TOTAL_COUNT);result->after_cat8=R32(GAME_COUNT);
    if(!context() || !home_idle(home) || R32(HOOK_SLOT)!=hook ||
        R32(home+0xdcu)!=home_queue || !d88_app_refresh_available() ||
        result->after_total>128u || result->after_cat8>result->after_total)
        return D88_FILE_E_PROFILE;
    result->post_calls=1u;posted=POST(home,0xb1u,0u,0u);
    result->post_result=(u32)posted;
    /* A scan is already complete if PAINT queuing fails. The caller receives
     * the partial-progress report and must not automatically scan a second time.
     */
    if(posted) return D88_FILE_E_IO;
    if(!context() || !home_idle(home) || R32(HOOK_SLOT)!=hook ||
        R32(home+0xdcu)!=home_queue) return D88_FILE_E_PROFILE;
    return 0;
}
